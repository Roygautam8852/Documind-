"""Server-side citation extraction, validation, and metadata mapping."""

from __future__ import annotations

import re

from app.providers.vector_store.base import VectorSearchResult
from app.schemas.chat import CitationItem

# Matches citation markers like [S1], [S2], [S10]
_CITATION_REGEX = re.compile(r"\[(S\d+)\]")


class CitationService:
    """Extracts and validates citations against server-retrieved chunks."""

    @classmethod
    def extract_citation_tags(cls, text: str) -> list[str]:
        """Extract ordered, deduplicated citation IDs from model response text."""
        seen: set[str] = set()
        citations: list[str] = []
        for match in _CITATION_REGEX.finditer(text):
            tag = match.group(1)
            if tag not in seen:
                seen.add(tag)
                citations.append(tag)
        return citations

    @classmethod
    def validate_citations(
        cls,
        answer: str,
        source_map: dict[str, tuple[VectorSearchResult, str]],
    ) -> list[CitationItem]:
        """Extract citation tags from answer, validate against source_map, and attach snippets.

        Any citation tag that does not exist in `source_map` is strictly rejected
        as a hallucinated citation and omitted from the response.

        Args:
            answer: Raw text response generated by the LLM.
            source_map: Map of "S1" -> (VectorSearchResult, filename) from prompt building.

        Returns:
            List of verified CitationItem objects in order of appearance.
        """
        tags = cls.extract_citation_tags(answer)
        validated: list[CitationItem] = []

        for tag in tags:
            entry = source_map.get(tag)
            if entry is None:
                # Fabricated/unknown citation: drop it
                continue

            chunk, filename = entry
            validated.append(
                CitationItem(
                    citation_id=tag,
                    document_id=chunk.document_id,
                    filename=filename,
                    page_number=chunk.page_number,
                    chunk_id=chunk.chunk_id,
                    snippet=chunk.text,
                )
            )

        return validated
