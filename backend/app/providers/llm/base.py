"""Abstract base interface for Large Language Model (LLM) providers."""

from __future__ import annotations

from abc import ABC, abstractmethod


class BaseLLMProvider(ABC):
    """Abstract interface for LLM response generation."""

    @property
    @abstractmethod
    def model_name(self) -> str:
        """Name or identifier of the underlying LLM model."""
        ...

    @abstractmethod
    async def generate(
        self,
        prompt: str,
        system_prompt: str | None = None,
        max_tokens: int = 1024,
        temperature: float = 0.0,
    ) -> str:
        """Generate a completion for the given prompt and system instructions.

        Args:
            prompt: Formatted user prompt with context.
            system_prompt: Optional system-level instructions and constraints.
            max_tokens: Maximum tokens in generated completion.
            temperature: Sampling temperature (0.0 for greedy, deterministic output).

        Returns:
            The raw text string generated by the model.
        """
        ...
